import fs from 'node:fs';

export const PROJECT='godot/chibi_remake';
export const SNAPSHOT='tools/inputs/runtime_assets.sha256';
export const isBinaryAsset=file=>/\.(png|jpe?g|svg|ico|otf|ttf|wav|ogg|avi|dll)$/i.test(file);
export const isAssetFile=file=>isBinaryAsset(file)||/\.(import|(?:png|jpe?g|svg|otf|ttf|wav|ogg|avi)\.uid)$/i.test(file)||file.startsWith(PROJECT+'/media/');
export const usesLfs=file=>isBinaryAsset(file)&&!/\.svg$/i.test(file);

export function readAssets(file=SNAPSHOT) {
 const rows=fs.readFileSync(file,'utf8').split(/\r?\n/).filter(Boolean).map(line=>{
  const [sha256,bytes,path,metadata='']=line.split('\t');
  if(!/^[a-f0-9]{64}$/.test(sha256)||!Number.isSafeInteger(Number(bytes))||Number(bytes)<1||!path||path.includes('..')||path.startsWith('/')||path.includes('\\')||!isBinaryAsset(path))throw Error('Invalid runtime asset row: '+line);
  const suffixes=metadata?metadata.split(','):[];
  if(suffixes.some(s=>!['.import','.uid'].includes(s)))throw Error('Invalid asset metadata: '+path);
  return {sha256,bytes:Number(bytes),path,metadata:suffixes};
 });
 if(new Set(rows.map(row=>row.path)).size!==rows.length)throw Error('Duplicate runtime assets');
 return rows;
}

export function assetFiles(rows) {
 return rows.flatMap(row=>[row.path,...row.metadata.map(suffix=>row.path+suffix)]).sort();
}

export function collectAssets(inputs,project=PROJECT) {
 return inputs.filter(isBinaryAsset).sort().map(path=>({path,metadata:['.import','.uid'].filter(suffix=>{
  // Terrain is decoded from raw JPEG bytes in both the source project and packer.
  if(path.startsWith('art/full/terrain_chunks/')&&suffix==='.import')return false;
  return fs.existsSync(project+'/'+path+suffix);
 })}));
}

export function ignoreAllowlist(rows) {
 const chunks='art/full/terrain_chunks/';
 const lines=['# BEGIN RUNTIME ASSETS (generated by node tools/runtime_assets.mjs --write)',
  '!/'+PROJECT+'/media/music/','!/'+PROJECT+'/media/sfx/','!/'+PROJECT+'/media/videos/'];
 for(const file of assetFiles(rows))if(!file.startsWith(chunks))lines.push('!/'+PROJECT+'/'+file);
 lines.push('# END RUNTIME ASSETS');
 return lines.join('\n');
}
